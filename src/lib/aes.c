/* round keyler icin rcon degerleri */
static const uint8_t rcon[] = { 0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36 };

/* GF(2^8) icinde x * 2 */
static uint8_t xtime(uint8_t x) {
    return (x << 1) ^ ((x >> 7) ? 0x1b : 0x00);
}

/* ---- yardimci GF carpanlari (InvMixColumns icin) ---- */
static uint8_t gf_mul9(uint8_t x)  { uint8_t x2=xtime(x), x4=xtime(x2), x8=xtime(x4); return x8 ^ x; }
static uint8_t gf_mul11(uint8_t x) { uint8_t x2=xtime(x), x8=xtime(xtime(x2));         return x8 ^ x2 ^ x; }
static uint8_t gf_mul13(uint8_t x) { uint8_t x2=xtime(x), x4=xtime(x2), x8=xtime(x4); return x8 ^ x4 ^ x; }
static uint8_t gf_mul14(uint8_t x) { uint8_t x2=xtime(x), x4=xtime(x2), x8=xtime(x4); return x8 ^ x4 ^ x2; }

/*
 * AES key expansion (128-bit). rk[176] = 11 round key, her biri 16 bayt.
 * Word bazli: ilk 4 kelime key'in kendisi, sonraki her kelime oncekiyle ve
 * 4 geridekiyle xorlanir; her 4. kelimede RotWord + SubWord + Rcon.
 */
void aes128_key_expand(const uint8_t key[16], uint8_t rk[AES_ROUND_KEYS]) {
    memcpy(rk, key, 16);
    uint8_t t[4];
    for (int i = 4; i < 44; i++) {
        t[0] = rk[4 * (i - 1) + 0];
        t[1] = rk[4 * (i - 1) + 1];
        t[2] = rk[4 * (i - 1) + 2];
        t[3] = rk[4 * (i - 1) + 3];
        if ((i & 3) == 0) {                       /* her 4. kelimede */
            uint8_t a = t[0];                     /* RotWord: saga kaydir */
            t[0] = t[1]; t[1] = t[2]; t[2] = t[3]; t[3] = a;
            t[0] = sbox[t[0]];                    /* SubWord */
            t[1] = sbox[t[1]];
            t[2] = sbox[t[2]];
            t[3] = sbox[t[3]];
            t[0] ^= rcon[i / 4 - 1];              /* Rcon */
        }
        rk[4 * i + 0] = rk[4 * (i - 4) + 0] ^ t[0];
        rk[4 * i + 1] = rk[4 * (i - 4) + 1] ^ t[1];
        rk[4 * i + 2] = rk[4 * (i - 4) + 2] ^ t[2];
        rk[4 * i + 3] = rk[4 * (i - 4) + 3] ^ t[3];
    }
}

/* ShiftRows: satir r, r kez sola dondurulur (state sutun-major). */
static void aes_shift_rows(uint8_t s[16]) {
    uint8_t t;
    t = s[1];  s[1]  = s[5];  s[5]  = s[9];  s[9]  = s[13]; s[13] = t;
    t = s[2];  s[2]  = s[10]; s[10] = t;     t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[15]; s[15] = s[11]; s[11] = s[7];  s[7]  = s[3];  s[3]  = t;
}

/* InvShiftRows: satir r, r kez saga dondurulur. */
static void aes_inv_shift_rows(uint8_t s[16]) {
    uint8_t t;
    t = s[13]; s[13] = s[9];  s[9]  = s[5];  s[5]  = s[1];  s[1]  = t;
    t = s[2];  s[2]  = s[10]; s[10] = t;     t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[3];  s[3]  = s[7];  s[7]  = s[11]; s[11] = s[15]; s[15] = t;
}

/*
 * MixColumns: her sutun v' = M * v,  M = [[2,3,1,1],[1,2,3,1],[1,1,2,3],[3,1,1,2]]
 * out0 = 2a + 3b + c + d, vs. (GF(2^8) toplama = XOR).
 */
static void aes_mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 4; c++) {
        int i = 4 * c;
        uint8_t a = s[i], b = s[i+1], c0 = s[i+2], d = s[i+3];
        uint8_t a2 = xtime(a), b2 = xtime(b), c2 = xtime(c0), d2 = xtime(d);
        s[i]   = a2 ^ b ^ b2 ^ c0 ^ d;
        s[i+1] = a ^ b2 ^ c0 ^ c2 ^ d;
        s[i+2] = a ^ b ^ c2 ^ d ^ d2;
        s[i+3] = a2 ^ a ^ b ^ c0 ^ d2;
    }
}

/*
 * InvMixColumns: M^-1 = [[14,11,13,9],[9,14,11,13],[13,9,14,11],[11,13,9,14]]
 * out0 = 14a + 11b + 13c + 9d, vs.
 */
static void aes_inv_mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 4; c++) {
        int i = 4 * c;
        uint8_t a = s[i], b = s[i+1], c0 = s[i+2], d = s[i+3];
        s[i]   = gf_mul14(a) ^ gf_mul11(b) ^ gf_mul13(c0) ^ gf_mul9(d);
        s[i+1] = gf_mul9(a)  ^ gf_mul14(b) ^ gf_mul11(c0) ^ gf_mul13(d);
        s[i+2] = gf_mul13(a) ^ gf_mul9(b)  ^ gf_mul14(c0) ^ gf_mul11(d);
        s[i+3] = gf_mul11(a) ^ gf_mul13(b) ^ gf_mul9(c0)  ^ gf_mul14(d);
    }
}

static void aes_add_round_key(uint8_t s[16], const uint8_t *rk) {
    for (int i = 0; i < 16; i++) s[i] ^= rk[i];
}

/*
 * Tek blok (16 bayt) sifreleme.
 * Round 0: AddRoundKey. Round 1-9: SB/SR/MC/ARK. Round 10: SB/SR/ARK (MC yok).
 */
void aes128_encrypt_block(const uint8_t in[16], const uint8_t rk[AES_ROUND_KEYS],
                          uint8_t out[16]) {
    uint8_t s[16];
    memcpy(s, in, 16);
    aes_add_round_key(s, rk);
    for (int r = 1; r <= 10; r++) {
        for (int i = 0; i < 16; i++) s[i] = sbox[s[i]];
        aes_shift_rows(s);
        if (r < 10) aes_mix_columns(s);
        aes_add_round_key(s, rk + 16 * r);
    }
    memcpy(out, s, 16);
}

/*
 * Tek blok (16 bayt) cozum. Ters siralamayla yapilir; round keyler
 * ayni expand edilmis dizi kullanilir, geriye dogru okunur.
 */
void aes128_decrypt_block(const uint8_t in[16], const uint8_t rk[AES_ROUND_KEYS],
                          uint8_t out[16]) {
    uint8_t s[16];
    memcpy(s, in, 16);
    aes_add_round_key(s, rk + 160);
    for (int r = 9; r >= 1; r--) {
        aes_inv_shift_rows(s);
        for (int i = 0; i < 16; i++) s[i] = inv_sbox[s[i]];
        aes_add_round_key(s, rk + 16 * r);
        aes_inv_mix_columns(s);
    }
    aes_inv_shift_rows(s);
    for (int i = 0; i < 16; i++) s[i] = inv_sbox[s[i]];
    aes_add_round_key(s, rk);
    memcpy(out, s, 16);
}
